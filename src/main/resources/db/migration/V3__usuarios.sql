CREATE TABLE usuarios (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 correo VARCHAR(150) NOT NULL UNIQUE,
 nombre VARCHAR(150) NOT NULL,
 clave_hash VARCHAR(100) NOT NULL,
 rol VARCHAR(30) NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 estudiante_id BIGINT NULL UNIQUE,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_usuario_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes(id),
 CONSTRAINT ck_usuario_rol CHECK (rol IN ('COORDINADOR','PROFESOR_UBB','PROFESOR_COLEGIO','ESTUDIANTE')),
 CONSTRAINT ck_usuario_estudiante CHECK ((rol='ESTUDIANTE' AND estudiante_id IS NOT NULL) OR (rol<>'ESTUDIANTE' AND estudiante_id IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
